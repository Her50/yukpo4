const sections = ['mesBesoinsLivres', 'adminDonations', 'bookSmartAutocomplete'];

let updated = 0;
let skipped = 0;

for (const file of files) {
    const langCode = file.replace('.json', '');
    const filePath = path.join(localesDir, file);

    try {
        const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
        let changed = false;

        for (const section of sections) {
            if (!data[section]) {
                // Use language-specific translation if available, else FR template
                const langTrans = translations[langCode];
                data[section] = (langTrans && langTrans[section]) ? langTrans[section] : frTemplate[section];
                changed = true;
            } else {
                // Section exists — add missing keys only
                const source = (translations[langCode] && translations[langCode][section])
                    ? translations[langCode][section]
                    : frTemplate[section];
                for (const [key, value] of Object.entries(source)) {
                    if (data[section][key] === undefined) {
                        data[section][key] = value;
                        changed = true;
                    }
                }
            }
        }

        if (changed) {
            fs.writeFileSync(filePath, JSON.stringify(data, null, 4), 'utf8');
            updated++;
            console.log(`✅ ${file} — updated`);
        } else {
            skipped++;
            console.log(`⏭️  ${file} — already up to date`);
        }
    } catch (err) {
        console.error(`❌ Error processing ${file}:`, err.message);
    }
}

