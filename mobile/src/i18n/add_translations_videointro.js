const langCodes = Object.keys(translations);
const allKeys = Object.keys(translations.fr);

let updatedCount = 0;
let errorCount = 0;

for (const lang of langCodes) {
  const filePath = path.join(LOCALES_DIR, `${lang}.json`);
  try {
    if (!fs.existsSync(filePath)) {
      console.log(`[SKIP] ${lang}.json: file not found`);
      continue;
    }

    const raw = fs.readFileSync(filePath, 'utf-8');
    const data = JSON.parse(raw);

    if (!data.videoIntro) {
      data.videoIntro = {};
    }

    let addedKeys = 0;
    for (const key of allKeys) {
      if (data.videoIntro[key] === undefined) {
        data.videoIntro[key] = translations[lang][key];
        addedKeys++;
      }
    }

    if (addedKeys > 0) {
      fs.writeFileSync(filePath, JSON.stringify(data, null, 4) + '\n', 'utf-8');
      console.log(`[OK] ${lang}.json: added ${addedKeys} keys to videoIntro`);
      updatedCount++;
    } else {
      console.log(`[OK] ${lang}.json: all videoIntro keys already present`);
    }
  } catch (err) {
    console.error(`[ERROR] ${lang}.json: ${err.message}`);
    errorCount++;
  }
}

console.log(`\nDone. Updated: ${updatedCount}, Errors: ${errorCount}`);
console.log(`Total languages covered: ${langCodes.length}`);
console.log(`Total keys per language: ${allKeys.length}`);
